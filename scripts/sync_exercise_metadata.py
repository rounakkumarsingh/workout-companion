#!/usr/bin/env python3
"""
Keep docs/domain/exercise-metadata.md in step with the program data.

The doc is a derived artifact, so its per-exercise tables, the presence summary
and the video index are generated, not hand-edited:

  * prescriptions (technique, warm-up, sets, reps, rest, which weeks and days an
    exercise appears in) come from src/data/program.ts, which verify_program.py
    proves equal to docs/program.pdf. The PDF's own day heading is unreliable,
    so days are taken from program.ts, never from the extraction.
  * substitution options, notes and the exercise's demo video come from
    docs/extraction/program.extracted.json (produced by extract_program.py).

The doc's layout (sections, entry order, intro text) is kept; only the table
values, the summary table and the video index are rewritten.

    python3 scripts/sync_exercise_metadata.py          # rewrite the doc
    python3 scripts/sync_exercise_metadata.py --check  # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import verify_program as vp  # noqa: E402  (parser for program.ts)

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "domain" / "exercise-metadata.md"
EXTRACTION = ROOT / "docs" / "extraction" / "program.extracted.json"
PROGRAM_TS = ROOT / "src" / "data" / "program.ts"
DAY_ORDER = ["Upper", "Lower", "Pull", "Push", "Legs"]
FOUNDATION_LAST_WEEK = 5
FIELD_ORDER = [
    "Day", "Block", "Technique", "Warm-Up Sets", "Working Sets", "Rep Range", "Rest",
    "Sub Option 1", "Sub Option 2", "Notes", "Demo",
]

VIDEO_NOTE_OLD_START = "**Video URL mapping**"
VIDEO_NOTE_NEW = (
    "**Video URL mapping**: Each exercise's `Demo` is the YouTube link the PDF attaches to the "
    "exercise name, read programmatically by `scripts/extract_program.py` (not inferred from "
    "document order). Substitution options carry their own links in the PDF; those are in "
    "`docs/extraction/program.extracted.json`. This file is generated by "
    "`scripts/sync_exercise_metadata.py`; do not edit the tables by hand."
)


# ---------------------------------------------------------------- model ----
class Exercise:
    def __init__(self, name: str) -> None:
        self.name = name
        # day -> week -> program.ts row
        self.rows: dict[str, dict[int, dict]] = collections.defaultdict(dict)
        # week -> extraction record (options, notes, video)
        self.ext: dict[int, dict] = {}

    @property
    def weeks(self) -> list[int]:
        return sorted({w for d in self.rows.values() for w in d})

    @property
    def days(self) -> list[str]:
        return [d for d in DAY_ORDER if d in self.rows] + [d for d in self.rows if d not in DAY_ORDER]


def build_model() -> dict[str, Exercise]:
    by_week, _videos, problems = vp.parse_program(PROGRAM_TS.read_text())
    if problems:
        raise SystemExit(f"program.ts could not be parsed cleanly: {problems[:2]}")
    model: dict[str, Exercise] = {}
    for week, days in by_week.items():
        for day, rows in days.items():
            for row in rows:
                model.setdefault(row["name"], Exercise(row["name"])).rows[day][week] = row
    extraction = json.loads(EXTRACTION.read_text())
    for rec in extraction["days"]:
        for e in rec["exercises"]:
            if e["name"] in model:
                model[e["name"]].ext.setdefault(rec["week"], e)
    return model


# -------------------------------------------------------------- render ----
def dash(value: str) -> str:
    return value.replace("-", "–")


def week_span(a: int, b: int) -> str:
    return f"W{a}" if a == b else f"W{a}–{b}"


def runs(series: dict[int, str]) -> list[tuple[int, int, str]]:
    out: list[tuple[int, int, str]] = []
    for week in sorted(series):
        value = series[week]
        if out and out[-1][2] == value and out[-1][1] == week - 1:
            out[-1] = (out[-1][0], week, value)
        else:
            out.append((week, week, value))
    return out


def series_text(series: dict[int, str]) -> str:
    r = runs(series)
    if len(r) == 1:
        return r[0][2]
    return ", ".join(f"{v} ({week_span(a, b)})" for a, b, v in r)


def per_day(ex: Exercise, pick) -> str:
    """One text when every day agrees, else 'Day: text; Day: text'."""
    texts = {day: series_text({w: pick(row) for w, row in ex.rows[day].items()}) for day in ex.days}
    if len(set(texts.values())) == 1:
        return next(iter(texts.values()))
    return "; ".join(f"{day}: {text}" for day, text in texts.items())


def warmup(row: dict) -> str:
    return str(row["wmin"]) if row["wmin"] == row["wmax"] else f"{row['wmin']}–{row['wmax']}"


def block_text(ex: Exercise) -> str:
    early = any(w <= FOUNDATION_LAST_WEEK for w in ex.weeks)
    late = any(w > FOUNDATION_LAST_WEEK for w in ex.weeks)
    return "Both" if early and late else ("Foundation only" if early else "Ramping only")


def option_text(ex: Exercise, slot: str) -> str:
    return series_text({w: e.get(slot) or "—" for w, e in ex.ext.items()})


def pick_note(ex: Exercise, current: str | None) -> str:
    raw = [e["notes"] for e in ex.ext.values() if e.get("notes")]
    if not raw:
        return current or "—"
    # The PDF drops or keeps a trailing full stop from week to week; keep the
    # doc's wording when it only differs in punctuation, to avoid churn.
    if current and any(fold(current) == fold(n) for n in raw):
        return current
    return collections.Counter(raw).most_common(1)[0][0]


def fold(text: str) -> str:
    return re.sub(r"[^a-z0-9]", "", (text or "").lower().replace("–", "-").replace("—", "-"))


def demo_text(ex: Exercise) -> str:
    ids = {e["video"] for e in ex.ext.values() if e.get("video")}
    if len(ids) > 1:
        raise SystemExit(f"{ex.name!r} has different demo videos across weeks: {sorted(ids)}")
    return f"`{next(iter(ids))}`" if ids else "—"


def expected_fields(ex: Exercise, current: dict[str, str]) -> dict[str, str]:
    return {
        "Day": ", ".join(ex.days),
        "Block": block_text(ex),
        "Technique": per_day(ex, lambda r: r["technique"]),
        "Warm-Up Sets": per_day(ex, warmup),
        "Working Sets": per_day(ex, lambda r: str(r["sets"])),
        "Rep Range": per_day(ex, lambda r: dash(r["reps"])),
        "Rest": per_day(ex, lambda r: dash(r["rest"])),
        "Sub Option 1": option_text(ex, "option1"),
        "Sub Option 2": option_text(ex, "option2"),
        "Notes": pick_note(ex, current.get("Notes")).replace("|", "\\|"),
        "Demo": demo_text(ex),
    }


# ----------------------------------------------------------------- doc ----
ENTRY = re.compile(r"^### (.+?)\n\n\| Field \| Value \|\n\|[-| ]+\|\n((?:\|.*\n)+)", re.M)


def parse_rows(block: str) -> dict[str, str]:
    out = {}
    for line in block.strip().split("\n"):
        key, value = [x.strip() for x in line.strip("|").split("|", 1)]
        out[key] = value
    return out


def video_id(demo: str) -> str:
    return demo.strip("`").rsplit("/", 1)[-1]


def sync(doc: str, model: dict[str, Exercise]) -> tuple[str, dict[str, int], list[str]]:
    changes: dict[str, int] = collections.Counter()
    notes: list[str] = []
    order: list[str] = []
    seen_fields: dict[str, dict[str, str]] = {}

    def rewrite(m: re.Match) -> str:
        name = m.group(1)
        ex = model.get(name)
        if ex is None:
            notes.append(f"doc entry {name!r} is not in program.ts; left unchanged")
            return m.group(0)
        order.append(name)
        current = parse_rows(m.group(2))
        wanted = expected_fields(ex, current)
        for key in FIELD_ORDER:
            if current.get(key) != wanted[key]:
                changes[key] += 1
        seen_fields[name] = wanted
        body = "".join(f"| {key} | {wanted[key]} |\n" for key in FIELD_ORDER)
        return f"### {name}\n\n| Field | Value |\n|-------|-------|\n{body}"

    out = ENTRY.sub(rewrite, doc)

    missing = [n for n in model if n not in order]
    if missing:
        notes.append(f"exercises in program.ts with no doc entry: {missing}")

    # Presence summary (same layout, regenerated rows in entry order).
    rows = ["| Exercise | Foundation (W1–5) | Ramping (W6–12) | Day |", "|----------|-------------------|-----------------|-----|"]
    for name in order:
        ex = model[name]
        early = "✓" if any(w <= FOUNDATION_LAST_WEEK for w in ex.weeks) else "—"
        late = "✓" if any(w > FOUNDATION_LAST_WEEK for w in ex.weeks) else "—"
        rows.append(f"| {name} | {early} | {late} | {' / '.join(ex.days)} |")
    summary = "\n".join(rows) + "\n"
    out, n = re.subn(r"\| Exercise \| Foundation \(W1–5\).*?\n(?=\n---)", lambda _m: summary, out, flags=re.S)
    if n != 1:
        notes.append("presence summary table not found")

    # Video index: one row per distinct exercise video, in entry order.
    by_video: dict[str, list[str]] = collections.OrderedDict()
    for name in order:
        demo = seen_fields[name]["Demo"]
        if demo != "—":
            by_video.setdefault(video_id(demo), []).append(name)
    index = ["| Video ID | Exercise(s) |", "|----------|-------------|"]
    index += [f"| `{vid}` | {', '.join(names)} |" for vid, names in by_video.items()]
    index_block = (
        "## Video Demo URL Index\n\n"
        "Each exercise's own demo link, as attached to its name in the PDF, as canonical `youtu.be` shortlinks "
        "(the PDF also uses `www.youtube.com/watch?v=` for some; they are normalised). "
        "An id shared by several exercises is a shared video in the PDF.\n\n"
        + "\n".join(index)
        + "\n"
    )
    out, n = re.subn(r"## Video Demo URL Index\n.*\Z", lambda _m: index_block, out, flags=re.S)
    if n != 1:
        notes.append("video index section not found")

    # Replace the stale paragraph describing how videos were mapped.
    out, n = re.subn(r"\*\*Video URL mapping\*\*:.*?(?=\n\n---)", lambda _m: VIDEO_NOTE_NEW, out, count=1, flags=re.S)
    if n != 1:
        notes.append("video mapping paragraph not found")
    return out, dict(changes), notes


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the doc is out of date; do not write")
    args = ap.parse_args()

    old = DOC.read_text()
    new, changes, notes = sync(old, build_model())
    for note in notes:
        print(f"note: {note}", file=sys.stderr)
    if changes:
        print("entries changed per field: " + ", ".join(f"{k}={v}" for k, v in changes.items()))
    if new == old:
        print("exercise-metadata.md is up to date")
        return 0
    if args.check:
        print("exercise-metadata.md is out of date: run python3 scripts/sync_exercise_metadata.py", file=sys.stderr)
        return 1
    DOC.write_text(new)
    print(f"rewrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
